#include <stdio.h>

int main()
{
    int a = -12;
    float b = 34.32;
    char c = 'P';
    long d = 764378265;
    double e = 23.345274784656;
    printf("The value of integer datatype is %d\n", a);
    printf("The value of float datatype is %.f\n", b);
    printf("The value of character datatype is %d\n", c);
    printf("The value of long datatype is %ld\n", d);
    printf("The value of double datatype is %.10lf\n", e);
    printf("The value of unsigned integer datatype is %u\n", a);
    return 0;
}