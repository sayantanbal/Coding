# print has many extra arguments like end, sep, etc. which can be used to customize the output

print(5, 6, 7, 8, sep=" ", end="!\n")
# sep --->> separator is used to specify what to print between the values in the line
# end --->> end parameter is used to specify what to print at the end of the line

# some more examples of sep and end
print(5, 6, 7, 8, sep=",", end="!\n")
print(5, 6, 7, 8, sep="*", end="!\n")
