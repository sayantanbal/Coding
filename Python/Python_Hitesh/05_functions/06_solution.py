# lambda function is a small anonymous function. It can take any number of arguments, but can only have one expression. 


cube = lambda x: x ** 3 # "lambda" is a keyword, x is the argument and x ** 3 is the expression. can only be used for small functions and used once.

print(cube(3)) # it is called like a normal function. parameter is passed in 1st bracket and the value is returned.